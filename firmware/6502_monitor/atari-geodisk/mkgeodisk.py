#!/usr/bin/env python3
"""Build GEODISK.SYS.

1. Assemble the resident handler (geodisk_res.s) at $2000 and at $2100 and
   compare the two images: every byte that differs by +1 is the high byte
   of a resident address (the installer moves the code to a page-aligned
   address, so low bytes never change).  Writes res.inc with the image and
   the relocation table.
2. Assemble the installer (geodisk.s, includes res.inc) at $6000 as a flat
   binary.
3. Wrap it into an Atari executable: one segment plus INITAD ($02E2), so
   the installer runs during the load and returns to DOS.
"""
import subprocess
import sys

CL65 = sys.argv[1] if len(sys.argv) > 1 else "cl65"
LOAD = 0x6000


def asm(src, start, out):
    subprocess.run([CL65, "-t", "none", "--start-addr", hex(start), "-o", out, src],
                   check=True)
    return open(out, "rb").read()


a = asm("geodisk_res.s", 0x2000, "res_2000.bin")
b = asm("geodisk_res.s", 0x2100, "res_2100.bin")
assert len(a) == len(b)
reloc = []
for i, (x, y) in enumerate(zip(a, b)):
    if x != y:
        assert (x + 1) & 0xFF == y, "byte %d: %02X -> %02X is not a high byte" % (i, x, y)
        reloc.append(i)
with open("res.inc", "w") as f:
    f.write("; generated by mkgeodisk.py: resident image linked at $2000\n")
    f.write("RES_SIZE = %d\nRELOC_N = %d\nres_image:\n" % (len(a), len(reloc)))
    for i in range(0, len(a), 16):
        f.write("        .byte " + ", ".join("$%02X" % c for c in a[i:i + 16]) + "\n")
    f.write("reloc_tab:\n")
    for i in range(0, len(reloc), 8):
        f.write("        .word " + ", ".join("$%04X" % c for c in reloc[i:i + 8]) + "\n")

body = asm("geodisk.s", LOAD, "geodisk.bin")
xex = bytearray(b"\xff\xff")
xex += bytes([LOAD & 0xFF, LOAD >> 8, (LOAD + len(body) - 1) & 0xFF, (LOAD + len(body) - 1) >> 8])
xex += body
xex += bytes([0xE2, 0x02, 0xE3, 0x02, LOAD & 0xFF, LOAD >> 8])     # INITAD
open("GEODISK.SYS", "wb").write(xex)
print("GEODISK.SYS: resident %d bytes, %d relocations, installer %d bytes, file %d bytes"
      % (len(a), len(reloc), len(body), len(xex)))
